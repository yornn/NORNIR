export const THREAT_DAYS = 2;

/**
 * День, с которого дитя вообще может выжить вне утробы.
 *
 * Семимесячных выхаживали и о них знали — «семимесячное дитя» отдельное
 * понятие в народном счёте. Всё, что раньше, в этом веке не жило.
 */
export const VIABLE_DAY = 210;

/** Ниже этого срока роды — всегда потеря, как ни старайся. */
const HOPELESS_DAY = 180;

/**
 * Накопленная тягота на сегодня.
 *
 * Каждая тягота слабеет со временем и сходит на нет к своему сроку. Складываем
 * то, что ещё действует: неделя, в которую случилось всё сразу, опаснее трёх
 * разных недель по одному разу.
 */
export function strainLoad(strain, today) {
    if (!strain?.length || !today) return 0;
    let load = 0;
    for (const item of strain) {
        const spec = STRAINS[item.id];
        if (!spec) continue;
        const age = daysSinceBleeding(item.at, today);
        if (age == null || age < 0 || age >= spec.days) continue;
        load += spec.weight * (1 - age / spec.days);
    }
    return load;
}

/** Тяготы, которые ещё действуют, — для панели и отладки. */
export function activeStrains(strain, today) {
    if (!strain?.length || !today) return [];
    return strain.filter((item) => {
        const spec = STRAINS[item.id];
        if (!spec) return false;
        const age = daysSinceBleeding(item.at, today);
        return age != null && age >= 0 && age < spec.days;
    }).map((item) => STRAINS[item.id]);
}

/**
 * Насколько утроба уязвима на этом сроке.
 *
 * Кривая не выдумана из головы: раньше всего теряют в первые недели, к
 * середине срока утроба держит крепче всего, а к концу любая встряска уже
 * не губит дитя, а торопит роды.
 */
export function termVulnerability(days) {
    if (days < 30) return 0.030;
    if (days < 90) return 0.020;
    if (days < HOPELESS_DAY) return 0.010;
    if (days < 240) return 0.015;
    return 0.025;
}

/**
 * Бросок: обернётся ли эта тягота угрозой.
 *
 * @param {object} ctx `{ chatId, today, conceived, termDays, load, strainId, chances }`
 * @returns {{chance:number, value:number, hit:boolean, outcome:string, savable:boolean}}
 */
export function rollThreat(ctx) {
    const chance = Math.max(0, Math.min(0.9,
        termVulnerability(ctx.termDays) * ctx.load * (ctx.risks?.threatScale ?? 1)));
    const seed = `threat|${ctx.chatId ?? "chat"}|${serialOf(ctx.today.year, ctx.today.month, ctx.today.day)}|${ctx.strainId}`;
    const value = hashUnit(seed);
    return {
        chance,
        value,
        hit: value < chance,
        /* До семи месяцев дитя не выживет, и роды тут — та же потеря.
           Дальше утроба уже не теряет, а торопится. */
        outcome: ctx.termDays < VIABLE_DAY ? "lost" : "labour",
        /* Половину угроз ещё можно отлежать. Какую именно — решено здесь же,
           чтобы «легла пластом» не превращалось в кнопку «отменить беду». */
        savable: hashUnit(`${seed}|save`) < 0.5,
    };
}

/**
 * Родилось ли дитя живым.
 *
 * Срок решает почти всё: до семи месяцев в этом веке не выхаживали никого.
 * Дальше остаётся то, что было всегда, — доля мертворождений, которую тягота
 * поднимает, но не создаёт.
 */
export const STILLBIRTH = {
    /* Доля мертворождений этого века — примерно каждое двадцатое. Это то,
       что было всегда, безо всякой тяготы. */
    base: 0.05,
    /* Роды до семи месяцев: дитя почти наверняка не задышит. */
    preterm: 0.55,
    /* Семь-восемь месяцев — «семимесячное дитя», выхаживали, но не всякое. */
    early: 0.15,
    /* За каждую единицу накопленной тяготы. */
    perStrain: 0.02,
};

export function rollStillbirth(ctx) {
    const days = ctx.termDays;
    if (days < HOPELESS_DAY) return { chance: 1, value: 0, still: true, early: true };

    const table = { ...STILLBIRTH, ...(ctx.risks?.stillbirth ?? {}) };
    const early = days < 240;
    const chance = Math.max(0, Math.min(0.95,
        table.base
        + (days < VIABLE_DAY ? table.preterm : 0)
        + (early ? table.early : 0)
        + (ctx.load ?? 0) * table.perStrain));
    const value = hashUnit(
        `still|${ctx.chatId ?? "chat"}|${serialOf(ctx.conceived.year, ctx.conceived.month, ctx.conceived.day)}`);
    return { chance, value, still: value < chance, early };
}

