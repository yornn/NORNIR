/**
 * Нужда дитяти на эту эйкту.
 *
 * @param {number} days Сколько дитяти дней
 * @param {object} today Дата сцены
 * @param {number|null} eykt Номер эйкты 0–7, если известен
 * @param {number} weekday День недели, 0 = Laugardagr
 * @param {string} seed Что-то своё у каждого дитяти, чтобы двойня не жила в такт
 */
export function childNeed(days, today, eykt, weekday, seed = "") {
    const fits = CHILD_NEEDS.filter((n) => {
        if (days < n.from || days > n.to) return false;
        if (n.weekday !== undefined && n.weekday !== weekday) return false;
        if (n.at && eykt !== null && !n.at.includes(eykt)) return false;
        return true;
    });
    if (!fits.length) return null;

    /* Сид держит нужду неизменной в пределах эйкты: свайп не перекидывает её,
       а следующая эйкта меняет. */
    const key = `need|${seed}|${serialOf(today.year, today.month, today.day)}|${eykt ?? "x"}`;

    /* Распорядок сильнее жребия: банный день не бросают кубиком. */
    const must = fits.find((n) => n.must);
    let picked = must;
    if (!picked) {
        const total = fits.reduce((sum, n) => sum + n.weight, 0);
        let point = hashUnit(key) * total;
        picked = fits.find((n) => (point -= n.weight) < 0) ?? fits[fits.length - 1];
    }
    const texts = picked.texts;
    return texts[Math.floor(hashUnit(`say|${key}`) * texts.length)];
}

/**
 * Сводка по дитяти — по одной на каждого.
 *
 * @param {object} child `{ born, name, sex }`
 * @param {object} today Дата сцены
 * @param {{eykt?: number|null, weekday?: number}} opts
 */
export function childSummary(child, today, opts = {}) {
    if (!child?.born || !today) return null;
    const days = serialOf(today.year, today.month, today.day)
        - serialOf(child.born.year, child.born.month, child.born.day);
    const stage = childStage(days);
    if (!stage) return null;

    return {
        days,
        age: childAge(days),
        stage,
        name: child.name ?? null,
        sex: child.sex ?? null,
        /* Пока не наречён — «дитя», и это не заглушка, а положение дел:
           до окропления водой у него нет ни имени, ни места в роду. */
        title: child.name ?? (child.sex === "m" ? "мальчик, не наречён" : child.sex === "f" ? "девочка, не наречена" : "дитя, не наречено"),
        need: childNeed(days, today, opts.eykt ?? null, opts.weekday ?? 0, child.born
            ? `${serialOf(child.born.year, child.born.month, child.born.day)}|${child.order ?? 0}`
            : ""),
    };
}

/**
 * Возраст словами — так, как сказала бы мать, а не как записал бы писарь.
 *
 * Ни «недель», ни «месяцев» в современном смысле: месяц здесь ровно
 * тридцатидневный и совпадает с календарным, поэтому счёт идёт по ним.
 */
export function childAge(days) {
    if (days < 1) return "родилось нынче";
    if (days < 10) return `${days} ${plural(days, "день", "дня", "дней")} от роду`;
    if (days < 30) return `вторая девятина`;
    const months = Math.floor(days / 30);
    if (months < 12) return `${months} ${plural(months, "месяц", "месяца", "месяцев")} от роду`;
    if (months === 12) return "год от роду";
    if (months < 18) return `год с ${months - 12} ${plural(months - 12, "месяцем", "месяцами", "месяцами")}`;
    if (months < 24) return "полтора года с лишком";
    return "два года — отнимать пора";
}

/* ============================================================
 * 4. ЗАЧАТИЕ
 *
 * Бросок детерминированный, и это обязательное требование, а не удобство.
 * Всё состояние в этом расширении выводится заново при каждом перерасчёте
 * чата — Math.random() давал бы новый исход на каждой перерисовке панели,
 * и беременность то появлялась бы, то исчезала.
 * ============================================================ */

/**
 * Шанс зачатия: базовый плюс надбавка за фазу, всё умножается на то,
 * пролилось ли семя внутрь.
 *
 * Формула нарочно простая и читается вслух: «два процента бывает всегда, плюс
 * двадцать три в открытые дни, а мимо — впятеро меньше».
 *
 *   opit:        (0.02 + 0.23) = 25%  внутрь,  5%   мимо
 *   hreinsun:    (0.02 + 0.06) =  8%  внутрь,  1.6% мимо
 *   thverrandi:  (0.02 + 0)    =  2%  внутрь,  0.4% мимо
 *   tidir:       (0.02 + 0)    =  2%  внутрь,  0.4% мимо
 *
 * Раньше это была таблица из восьми чисел, по два на фазу. Числа выходили те
 * же, но связь между ними приходилось держать в голове: почему «мимо» вчетверо
 * меньше в одной строке и впятеро в другой, никто уже не помнил.
 *
 * `withheld` — это НЕ противозачаточное средство. В XI веке прерванный акт
 * ровно то, чем он и был: заметно снижает шанс и ничего не гарантирует.
 */
export const CONCEPTION = {
    /** Бывает в любой день цикла: тело не календарь и сроки плавают. */
    base: 0.02,
    /** Надбавка за фазу. Открытое лоно — то самое окно. */
    phase: { tidir: 0, hreinsun: 0.06, opit: 0.23, thverrandi: 0 },
    /** Во сколько раз меньше, если семя пролилось мимо. */
    withheld: 0.2,
};

/** Доля верных гаданий о поле. Остальные — мимо, и это сюжет. */
export const DIVINATION_ACCURACY = 0.6;

/**
 * Сколько дитяти зараз.
 *
 * Числа человеческие, скандинавские: двойни в Северной Европе рождаются чаще,
 * чем где-либо, — около полутора процентов. Тройни — примерно одна на восемь
 * тысяч, то есть раз в жизни деревни.
 */
export const MULTIPLE_CHANCE = { twins: 0.015, triplets: 0.000125 };

/**
 * Число 0..1 из строки — FNV-1a с досыпкой (fmix32).
 *
 * Досыпка не украшение, а починка. Чистый FNV-1a на соседних строках даёт
 * соседние числа: у «sex|3421» и «sex|3422» совпадают старшие биты, а
 * trueSexOf смотрел именно на старший бит. Выходили длинные серии — десять
 * дней подряд сын, потом двадцать дочь. На практике это значило, что четыре
 * прогона с близкими датами зачатия давали одного и того же ребёнка, хотя
 * по всему диапазону доля честно держалась около половины.
 *
 * fmix32 из MurmurHash3 перемешивает биты так, что соседние сиды расходятся
 * полностью. Проверяется тестом: длина серий и доля по подряд идущим дням.
 */
export function hashUnit(seed) {
    let h = 0x811c9dc5;
    const text = String(seed);
    for (let i = 0; i < text.length; i++) {
        h ^= text.charCodeAt(i);
        h = Math.imul(h, 0x01000193) >>> 0;
    }
    /* Лавина: без неё старшие биты почти не зависят от последнего символа. */
    h ^= h >>> 16;
    h = Math.imul(h, 0x85ebca6b) >>> 0;
    h ^= h >>> 13;
    h = Math.imul(h, 0xc2b2ae35) >>> 0;
    h ^= h >>> 16;
    return (h >>> 0) / 0x100000000;
}

/**
 * Сид броска.
 *
 * Складывается из чата, дня сцены и дня цикла — намеренно без номера
 * сообщения. Номер это индекс в массиве: удалили реплику в начале истории,
 * и все прошлые броски пересчитались бы задним числом. Дата сцены не
 * сдвигается никогда, а свайп её не меняет — значит и бросок не перекинется.
 */
function conceptionSeed(chatId, today, cycleDayNumber) {
    return `${chatId ?? "chat"}|${serialOf(today.year, today.month, today.day)}|${cycleDayNumber}`;
}

/**
 * Шанс зачатия при этой близости.
 *
 * @param {string} phaseId Фаза цикла
 * @param {boolean} internal Пролилось ли внутрь
 * @param {object} [chances] Переопределение из настроек
 */
export function conceptionChance(phaseId, internal, chances = null) {
    const table = { ...CONCEPTION, ...(chances ?? {}) };
    const phase = table.phase?.[phaseId] ?? 0;
    const raw = (table.base ?? 0) + phase;
    return Math.max(0, Math.min(1, internal ? raw : raw * (table.withheld ?? 0)));
}

/**
 * Бросок на зачатие.
 *
 * @param {object} ctx `{ chatId, today, cycleDay, phaseId, internal, chances, modifiers }`
 * @returns {{chance:number, value:number, hit:boolean}}
 */
export function rollConception(ctx) {
    const base = conceptionChance(ctx.phaseId, ctx.internal, ctx.chances);
    /* Хук под возраст, голод и истощение — пока всегда единица. */
    const chance = Math.max(0, Math.min(1, base * (ctx.modifiers ?? 1)));
    const value = hashUnit(conceptionSeed(ctx.chatId, ctx.today, ctx.cycleDay));
    return { chance, value, hit: value < chance };
}

/**
 * Настоящий пол — решается один раз, в день зачатия, и кладётся в запись.
 *
 * Отдельный сид с чатом внутри: без него одна и та же дата зачатия давала
 * во ВСЕХ историях одного и того же ребёнка. Две ролевые с одинаковым началом
 * рожали одинаковых детей, и это замечалось.
 */
export function rollSex(chatId, conceived, order = 0) {
    const s = serialOf(conceived.year, conceived.month, conceived.day);
    return hashUnit(`sex|${chatId ?? "chat"}|${s}|${order}`) < 0.5 ? "m" : "f";
}

/** Пол каждого из двойни — по своему броску: разнояйцевые бывают разными. */
export function rollSexes(chatId, conceived, count = 1) {
    return Array.from({ length: Math.max(1, count) }, (_, i) => rollSex(chatId, conceived, i));
}

/**
 * Сколько дитяти в утробе. Решается там же и тогда же.
 *
 * Порядок проверок от редкого к частому: тройня — подмножество «больше одного»,
 * и если сначала отсечь двойню, тройни не случится никогда.
 */
export function rollBirths(chatId, conceived, chances = null) {
    const table = { ...MULTIPLE_CHANCE, ...(chances ?? {}) };
    const s = serialOf(conceived.year, conceived.month, conceived.day);
    const roll = hashUnit(`births|${chatId ?? "chat"}|${s}`);
    if (roll < (table.triplets ?? 0)) return 3;
    if (roll < (table.triplets ?? 0) + (table.twins ?? 0)) return 2;
    return 1;
}

/**
 * Пол дитяти по старой схеме — только для записей, заведённых до того, как
 * пол стали хранить. Новые беременности его не зовут.
 */
export function trueSexOf(conceived) {
    return hashUnit(`sex|${serialOf(conceived.year, conceived.month, conceived.day)}`) < 0.5 ? "m" : "f";
}

/** Пол из записи, а если её нет — по старой схеме. */
export function sexOf(pregnancy) {
    return pregnancy?.sex ?? trueSexOf(pregnancy.conceived);
}

