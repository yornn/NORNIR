/** Малый шанс не встать вовсе — только у спорыньи и только по тумблеру. */
export const HERB_DEATH_CHANCE = 0.12;

/** Травы, доступные в этом месяце. */
export function herbsInSeason(month) {
    return Object.values(HERBS).filter((h) => !h.months || h.months.some((m) => String(m) === String(month)));
}

/**
 * Какую траву дали.
 *
 * Выбор детерминированный — от чата и дня, как и всё здесь: пересчёт истории
 * не должен подменять траву задним числом.
 */
export function pickHerb(chatId, today) {
    const fits = herbsInSeason(today.month);
    if (!fits.length) return HERBS.einir;
    const total = fits.reduce((sum, h) => sum + h.weight, 0);
    let point = hashUnit(`herb|${chatId ?? "chat"}|${serialOf(today.year, today.month, today.day)}`) * total;
    return fits.find((h) => (point -= h.weight) < 0) ?? fits[fits.length - 1];
}

/**
 * Подействовал ли отвар и чем обернулся.
 *
 * @param {object} ctx `{ chatId, today, herb, pregnant, death }`
 */
export function rollHerb(ctx) {
    const seed = `draught|${ctx.chatId ?? "chat"}|${serialOf(ctx.today.year, ctx.today.month, ctx.today.day)}`;
    const value = hashUnit(seed);
    /* Небеременной отвар «срабатывает» всегда: кровь приходит, и героиня
       уверена, что трава помогла. Прерывать было нечего — но знать ей это
       неоткуда, и панель ей об этом не скажет. */
    const worked = !ctx.pregnant || value < ctx.herb.chance;
    const fatal = ctx.death && ctx.herb.toll === "dire"
        && hashUnit(`${seed}|death`) < HERB_DEATH_CHANCE;
    return { value, chance: ctx.herb.chance, worked, fatal };
}

/**
 * Что панель показывает про отвар, либо null — если откат уже прошёл.
 */
export function herbView(herb, today) {
    if (!herb) return null;
    const spec = HERBS[herb.id];
    const toll = HERB_TOLLS[spec?.toll];
    if (!spec || !toll) return null;

    const age = daysSinceBleeding(herb.at, today);
    if (age == null || age < 0) return null;

    const barrenLeft = toll.barren ? toll.barren - age : 0;
    if (age > toll.days && barrenLeft <= 0) return null;

    return {
        id: spec.id,
        herb: spec,
        toll,
        age,
        left: toll.days - age,
        /* Откат кончился, а последствие тянется — так бывает только у рожков. */
        lingering: age > toll.days,
        barrenLeft: Math.max(0, barrenLeft),
        fatal: !!herb.fatal,
        title: spec.norse ?? spec.ru,
        status: age > toll.days ? (toll.aftermath ?? toll.status) : toll.status,
        hint: toll.hint,
    };
}

/** Не примет ли утроба семени из-за отвара. */
export function herbBarren(herb, today) {
    const view = herbView(herb, today);
    return !!view && view.barrenLeft > 0;
}

