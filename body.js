/**
 * Как давно дитя подавало голос.
 *
 * В XI веке это единственный способ узнать, живо ли оно, — и главный источник
 * тревоги. Считается от последнего шевеления, поэтому затишье набегает само,
 * без всякого события: сцена просто перестала о нём писать.
 */
export function kickWatch(pregnancy, today, quickened) {
    if (!quickened) return null;

    /* Считаем от того, что случилось позже: сказанного затишья или последнего
       шевеления. Если ни того, ни другого — от самого квикнана: он и есть
       первое движение, и молчание после него уже что-то значит. */
    const silent = pregnancy?.quietSince ?? null;
    const from = silent ?? pregnancy?.lastKick ?? pregnancy?.quickened ?? null;
    if (!from) return null;

    const days = serialOf(today.year, today.month, today.day)
        - serialOf(from.year, from.month, from.day);
    if (days < 0) return null;

    if (silent) {
        if (days === 0) return { days, text: "Дитя притихло", alarm: true };
        if (days === 1) return { days, text: "Дитя притихло со вчера", alarm: true };
        if (days < 4) return { days, text: `Дитя тихо ${days} дня`, alarm: true };
        return { days, text: `Дитя не слыхать ${days} ${plural(days, "день", "дня", "дней")}`, alarm: true };
    }
    if (days === 0) return { days, text: "Дитя бьётся крепко", alarm: false };
    if (days === 1) return { days, text: "Дитя притихло со вчера", alarm: false };
    if (days < 4) return { days, text: `Дитя тихо ${days} дня`, alarm: true };
    return { days, text: `Дитя не слыхать ${days} ${plural(days, "день", "дня", "дней")}`, alarm: true };
}

/**
 * Одно слово из пула — на сутки.
 *
 * Сид складывается из дня сцены и якоря тела (зачатие или последняя кровь),
 * поэтому примета держится ровно сутки, не пляшет от свайпа к свайпу и у
 * разных героинь в один день разная. Номера сообщения в сиде нет намеренно:
 * он индекс в массиве, и удаление реплики перетасовало бы прошлое.
 */
function pickSign(group, seed) {
    return group.texts[Math.floor(hashUnit(`${seed}|${group.id}`) * group.texts.length)];
}

/**
 * Признаки, поспевшие к этой части срока.
 *
 * Возвращаем `{ kind, text }`, а не строки: панель рисует каждую примету своей
 * строкой со своим знаком, и склеивать их обратно в одну строку она не должна.
 *
 * Показываем все поспевшие — по одной строке на вид, — но слова каждый день
 * берутся из пула заново. Прежде список был плоским и фильтровался по части
 * срока: тридцать суток подряд панель твердила одно и то же теми же словами.
 *
 * @param {number} part Часть ношения, 1..9
 * @param {string} seed Якорь тела и день сцены; без него слова не меняются
 */
export function termSigns(part, seed = "") {
    return TERM_SIGNS
        .filter((g) => part >= g.from && part <= (g.to ?? Infinity))
        .map((g) => ({ kind: g.kind, text: pickSign(g, seed) }));
}

/**
 * Приметы по дню цикла — грудь, сон, запахи, отёки и нрав.
 *
 * Отёки здесь ничем не связаны с погодой, и это не упущение: они ходят за
 * циклом, а не за временем года. Погоду считает weatherToll() и только для
 * носящей.
 *
 * @param {number|null} day День цикла, 1..length
 * @param {number} length Длина цикла
 * @param {string} seed Якорь тела и день сцены
 */
export function cycleSigns(day, length = CYCLE_DEFAULT, seed = "") {
    if (day == null) return [];
    const len = normalizeCycleLength(length);
    const left = daysToBleeding(day, len);
    return CYCLE_SIGNS
        .filter((g) => {
            if (g.beforeBleed) return left <= g.beforeBleed;
            if (day < g.from || day > (g.to ?? len)) return false;
            /* Хвост цикла принадлежит предкровью: без этого грудь стояла бы
               двумя строками разом — и «потяжелела», и «каменная». */
            return g.minLeft == null || left > g.minLeft;
        })
        .map((g) => ({ kind: g.kind, text: pickSign(g, seed) }));
}

/**
 * Погода бьёт по телу, и это дёшево: погоду мы и так знаем из маркера.
 * Жара на девятой части — отёки и дурнота, мороз — ломота.
 */
export function weatherToll(weather, part) {
    if (!weather || !part || part < 4) return null;
    const w = String(weather).toLowerCase();
    if (/жар|зной|дух|пекл/.test(w)) return "В жару отекают ноги, дурнота подступает, дитя буйствует";
    if (/мороз|стуж|метел|снег|холод|ледян/.test(w)) return "Холод забирает силы, ломит поясницу";
    return null;
}

